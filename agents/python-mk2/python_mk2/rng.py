"""The piece RNG.

Every peer derives the same deterministic piece sequence from GameMeta.Seed, so
all boards spawn identical pieces without any coordination. This reproduces
the game's generator bit for bit: a 128-bit PCG-XSL-RR (the one Go's
math/rand/v2 uses), a Lemire bounded draw, and a Fisher-Yates shuffle. The
sequence is seekable: bag k is generated by PCG(seed, k), so any global piece
index is reachable in O(1) bags.
"""

M64 = (1 << 64) - 1
_M128 = (1 << 128) - 1
_MUL = (2549297995355413924 << 64) | 4865540595714422341
_INC = (6364136223846793005 << 64) | 1442695040888963407
_CHEAP = 0xDA942042E4DD58B5

FULL_BAG = (0, 1, 2, 3, 4, 5, 6)


class PCG:
    """The 128-bit PCG-XSL-RR state: hi is the seed, lo the stream."""

    __slots__ = ("state",)

    def __init__(self, hi, lo):
        self.state = ((hi & M64) << 64) | (lo & M64)

    def next(self):
        """Advance the generator and return the next 64-bit output."""
        s = (self.state * _MUL + _INC) & _M128
        self.state = s
        hi, lo = s >> 64, s & M64
        hi ^= hi >> 32
        hi = (hi * _CHEAP) & M64
        hi ^= hi >> 48
        return (hi * (lo | 1)) & M64

    def uint64n(self, n):
        """A uniform value in [0, n): Lemire's method, the power-of-two fast
        path and the biased-low rejection threshold included."""
        if n & (n - 1) == 0:
            return self.next() & (n - 1)
        prod = self.next() * n
        hi, lo = prod >> 64, prod & M64
        if lo < n:
            thresh = ((1 << 64) - n) % n
            while lo < thresh:
                prod = self.next() * n
                hi, lo = prod >> 64, prod & M64
        return hi

    def int_n(self, n):
        """rand/v2 Rand.IntN (64-bit platforms: the 64-bit bounded draw)."""
        return self.uint64n(n)

    def perm(self, n):
        """rand/v2 Rand.Perm: the identity shuffled by Rand.Shuffle."""
        p = list(range(n))
        for i in range(n - 1, 0, -1):
            j = self.uint64n(i + 1)
            p[i], p[j] = p[j], p[i]
        return p


def _shuffle(p, b):
    for i in range(len(b) - 1, 0, -1):
        j = p.uint64n(i + 1)
        b[i], b[j] = b[j], b[i]


def piece_at(seed, index):
    """The piece type (0..6) at the given global sequence index: the index's
    position within its 7-bag, drawn from a Fisher-Yates shuffle of that bag
    seeded by PCG(seed, bag_number)."""
    bag, pos = divmod(index, 7)
    b = [0, 1, 2, 3, 4, 5, 6]
    _shuffle(PCG(seed, bag), b)
    return b[pos]


# ---- the teams-mode piece split (meta split_pieces, gameplays §5) ----------
#
# A teams game may deal the seven piece types out between the teammates
# instead of giving every seat the same full bag: each seat holds a RATION of
# one or more types and its sequence is a bag of that ration alone, so the
# whole bag exists only across the team. The deal is the seed's, so every
# peer computes the same one, and both teams' slot N hold the same ration,
# which is what keeps the match fair.

# The PCG stream the deal is drawn from: bag streams count upwards from 0, so
# the deal takes the number no bag ever reaches.
DEAL_STREAM = M64


def piece_sets(seed, seats):
    """Deal the seven types among `seats` seats: every type goes to somebody,
    every seat gets at least one, and past seven seats the types start
    doubling up. Returns one ascending list per seat."""
    if seats <= 0:
        return []
    if seats == 1:
        return [list(FULL_BAG)]
    p = PCG(seed, DEAL_STREAM)
    order = list(range(seats))
    _shuffle(p, order)
    sets = [[] for _ in range(seats)]
    deck = []
    for i in range(max(seats, 7)):
        if i % 7 == 0:
            deck = list(FULL_BAG)
            _shuffle(p, deck)
        seat, pt = order[i % seats], deck[i % 7]
        if pt not in sets[seat]:
            sets[seat].append(pt)
    return [sorted(s) for s in sets]


def piece_set_for(seed, seats, slot):
    """The ration held by seat `slot` of a `seats`-seat team. A slot outside
    the deal holds the whole bag."""
    sets = piece_sets(seed, seats)
    if slot < 0 or slot >= len(sets):
        return list(FULL_BAG)
    return sets[slot]


def ration_seed(seed, ration):
    """The stream a ration draws its bags from: the game's seed mixed
    (splitmix64) with the ration's 7-bit mask, so different rations shuffle
    independently and one ration draws the same order wherever it is held.
    The full bag keeps the raw seed (piece_at)."""
    mask = 0
    for pt in ration:
        mask |= 1 << pt
    x = (seed + 0x9E3779B97F4A7C15 * (mask + 1)) & M64
    x ^= x >> 30
    x = (x * 0xBF58476D1CE4E5B9) & M64
    x ^= x >> 27
    x = (x * 0x94D049BB133111EB) & M64
    x ^= x >> 31
    return x


def piece_at_in(seed, ration, index):
    """piece_at over a ration: the index's position within a shuffle of that
    ration (a bag of len(ration) pieces, not seven). An empty ration is the
    full bag."""
    n = len(ration)
    if n == 0:
        return piece_at(seed, index)
    bag, pos = divmod(index, n)
    b = list(ration)
    _shuffle(PCG(ration_seed(seed, ration), bag), b)
    return b[pos]


# ---- the bag rule (meta bag, gameplays §1b) --------------------------------
#
# A game's meta may deal its pieces with something other than the standard
# 7-bag: "double" is the double bag (two of every type shuffled together,
# fourteen at a time, 2k for a ration of k) and "none" is no bag at all:
# every piece an independent uniform draw from the set, the first pick off
# PCG(seed, index). Absent, or anything else, is the 7-bag. The rule shapes a
# split-pieces ration the same way, and the ration keeps its mixed stream
# (ration_seed) under every kind.

BAG_SINGLE = ""
BAG_DOUBLE = "double"
BAG_NONE = "none"


def normalize_bag(kind):
    """A meta's bag kind: the two named kinds as themselves, anything else
    (absent, a kind this build does not know) as the 7-bag."""
    return kind if kind in (BAG_DOUBLE, BAG_NONE) else BAG_SINGLE


def bag_label(kind):
    return {BAG_DOUBLE: "double bag", BAG_NONE: "no bag"}.get(normalize_bag(kind), "7-bag")


def piece_at_bag(seed, ration, kind, index):
    """The piece at index of the sequence over ration (the seven types when it
    is empty) dealt with the given bag kind."""
    if ration:
        pset, stream = list(ration), ration_seed(seed, ration)
    else:
        pset, stream = list(FULL_BAG), seed
    kind = normalize_bag(kind)
    if kind == BAG_NONE:
        return pset[PCG(stream, index).uint64n(len(pset))]
    if kind == BAG_DOUBLE:
        b = pset + pset
        bag, pos = divmod(index, len(b))
        _shuffle(PCG(stream, bag), b)
        return b[pos]
    if not ration:
        return piece_at(seed, index)
    return piece_at_in(seed, ration, index)
